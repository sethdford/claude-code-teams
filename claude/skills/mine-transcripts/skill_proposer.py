#!/usr/bin/env python3
"""
Skill auto-proposer (Phase H1, Voyager-style for code).

Watches mining-run extractions for recurring multi-step patterns (≥3 occurrences)
and drafts NEW SKILL.md candidates to ~/.claude/rl/policy/skill-candidates/
for human review.

Anthropic's Agent Skills (Oct 2025) is the production realization of Voyager's
skill-library idea — frontmatter-only at session start, body on demand. This
script closes the loop: trajectory miner finds patterns → proposes new skills
→ human approves → installed.

Usage:
  skill_proposer.py --run-dir ~/.claude/telemetry/mining-runs/<ts>/
  skill_proposer.py --rebuild  # walk all runs in the last 30d

Output:
  ~/.claude/rl/policy/skill-candidates/<slug>.md  (proposed SKILL.md)
  ~/.claude/rl/policy/skill-candidates/<slug>.evidence.json  (source patterns + run refs)

The proposed SKILL.md is a draft — frontmatter, when_to_use, body sketch.
Human reviews, edits if needed, runs /eval-author on it, and if it survives
moves it to ~/.claude/skills/<name>/SKILL.md.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

RL_POLICY_DIR = Path.home() / ".claude" / "rl" / "policy" / "skill-candidates"
TELEMETRY = Path.home() / ".claude" / "telemetry"
MIN_OCCURRENCES = 3
MAX_CANDIDATES_PER_RUN = 5


def slugify(text: str, max_len: int = 50) -> str:
    s = re.sub(r"[^\w\s-]", "", text.lower()).strip()
    s = re.sub(r"[-\s]+", "-", s)
    s = re.sub(r"^[-_]+|[-_]+$", "", s)
    return s[:max_len] or "candidate"


def collect_patterns(run_dirs: list[Path]) -> list[dict]:
    """
    Walk extractions across runs. Returns flat list of pattern records:
      {summary, evidence, tags, source_run, source_session}
    """
    out: list[dict] = []
    for run_dir in run_dirs:
        ext_dir = run_dir / "extractions"
        if not ext_dir.exists():
            continue
        for ej in ext_dir.glob("*.json"):
            try:
                data = json.loads(ej.read_text())
            except json.JSONDecodeError:
                continue
            sid = ej.stem
            for p in data.get("patterns", []) or []:
                out.append({
                    **p,
                    "source_run": run_dir.name,
                    "source_session": sid,
                })
    return out


def cluster_patterns(patterns: list[dict]) -> list[dict]:
    """
    Group patterns by lexical similarity on the summary (no embeddings; keyword overlap).
    Returns: list of {representative, count, occurrences: [pattern, ...]}
    """
    # Simple token-overlap clustering
    def token_set(s: str) -> set[str]:
        return {t for t in re.findall(r"[a-z][a-z0-9_-]{2,}", s.lower())}

    clusters: list[list[dict]] = []
    for p in patterns:
        ptoks = token_set(p["summary"])
        if not ptoks:
            continue
        placed = False
        for c in clusters:
            ctoks = token_set(c[0]["summary"])
            jaccard = len(ptoks & ctoks) / max(1, len(ptoks | ctoks))
            if jaccard >= 0.4:  # 40% token overlap = same cluster
                c.append(p)
                placed = True
                break
        if not placed:
            clusters.append([p])

    out: list[dict] = []
    for c in clusters:
        if len(c) < MIN_OCCURRENCES:
            continue
        out.append({
            "representative": c[0],
            "count": len(c),
            "occurrences": c,
            "all_tags": list({t for o in c for t in (o.get("tags") or [])}),
        })
    out.sort(key=lambda x: -x["count"])
    return out[:MAX_CANDIDATES_PER_RUN]


def draft_skill_md(cluster: dict) -> str:
    """Generate a SKILL.md draft for a clustered pattern."""
    rep = cluster["representative"]
    summary = rep["summary"]
    slug = slugify(summary)
    name = slug.replace("-", "-")  # name is the slug

    # Trigger phrases — pull verbs/nouns from the summary
    tokens = re.findall(r"[a-zA-Z][a-zA-Z0-9-]{2,}", summary)
    keywords = ", ".join(f'"{t}"' for t in tokens[:5])

    # Body: list the evidence excerpts from each occurrence
    evidence_bullets = []
    for o in cluster["occurrences"][:5]:
        ev = (o.get("evidence") or "")[:200].replace("\n", " ")
        evidence_bullets.append(f"- _Session {o.get('source_session', 'unknown')[:8]}_: {ev}")
    evidence_block = "\n".join(evidence_bullets)

    md = f"""---
name: {name}
description: PROPOSED CANDIDATE — {summary}. Generated by skill auto-proposer from {cluster['count']} observed occurrences. Triggers on phrases like {keywords}.
when_to_use: This is a CANDIDATE skill awaiting human review. Do NOT auto-invoke until promoted to ~/.claude/skills/{name}/SKILL.md.
allowed-tools: Read, Glob, Grep, Bash, Edit, Write
disable-model-invocation: true
---

# /{name} — PROPOSED (review before promoting)

> Auto-generated by `skill_proposer.py` from {cluster['count']} observed occurrences across mining runs. **Do not promote without review.**

## What this skill would do

{summary}

## Observed evidence

{evidence_block}

## Proposed body (REVIEW + EDIT)

When invoked, this skill should:

1. (TODO: distill from the evidence above — what is the recurring procedure?)
2. (TODO: identify the inputs / outputs / contracts)
3. (TODO: list the anti-patterns the skill should refuse)

## Promotion checklist

- [ ] Review evidence — does this generalize, or is it project-specific?
- [ ] Edit name/description for clarity (auto-generated names are heuristic)
- [ ] Distill the procedure into clear numbered steps
- [ ] Add 2-3 anti-patterns
- [ ] Run `/eval-author {name}` to generate scenarios
- [ ] Run `/eval {name}` against the scenarios — needs ≥3 passing before promotion
- [ ] Move to `~/.claude/skills/{name}/SKILL.md` (drop `disable-model-invocation: true`)

## Tags
{', '.join(cluster['all_tags']) or '(none)'}
"""
    return md


def write_candidate(cluster: dict) -> tuple[Path, Path]:
    RL_POLICY_DIR.mkdir(parents=True, exist_ok=True)
    rep = cluster["representative"]
    slug = slugify(rep["summary"])

    md_path = RL_POLICY_DIR / f"{slug}.md"
    evidence_path = RL_POLICY_DIR / f"{slug}.evidence.json"

    md_path.write_text(draft_skill_md(cluster))
    evidence_path.write_text(json.dumps({
        "slug": slug,
        "summary": rep["summary"],
        "count": cluster["count"],
        "occurrences": cluster["occurrences"],
        "all_tags": cluster["all_tags"],
        "drafted_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }, indent=2))

    return md_path, evidence_path


def main() -> int:
    ap = argparse.ArgumentParser()
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--run-dir", type=Path, help="Single mining run dir")
    src.add_argument("--rebuild", action="store_true", help="Walk all mining-runs in last 30 days")
    args = ap.parse_args()

    if args.run_dir:
        run_dirs = [args.run_dir]
    else:
        runs = TELEMETRY / "mining-runs"
        if not runs.exists():
            print("[skill-proposer] no mining-runs/ — run /mine-transcripts first", file=sys.stderr)
            return 1
        run_dirs = sorted(runs.glob("*"))[-30:]  # last 30 runs

    patterns = collect_patterns(run_dirs)
    if not patterns:
        print(json.dumps({"candidates": 0, "reason": "no patterns extracted"}, indent=2))
        return 0

    clusters = cluster_patterns(patterns)
    if not clusters:
        print(json.dumps({
            "candidates": 0,
            "reason": f"no patterns met min_occurrences={MIN_OCCURRENCES}",
            "patterns_seen": len(patterns),
        }, indent=2))
        return 0

    written: list[dict] = []
    for cluster in clusters:
        md_path, evidence_path = write_candidate(cluster)
        written.append({
            "candidate": str(md_path.relative_to(Path.home())),
            "evidence": str(evidence_path.relative_to(Path.home())),
            "summary": cluster["representative"]["summary"],
            "count": cluster["count"],
        })

    # Log to telemetry
    log_path = TELEMETRY / "skill-proposer.jsonl"
    with log_path.open("a") as f:
        f.write(json.dumps({
            "ts": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "n_runs": len(run_dirs),
            "n_patterns_seen": len(patterns),
            "n_candidates_drafted": len(written),
        }) + "\n")

    print(json.dumps({
        "candidates": len(written),
        "drafted": written,
        "review_dir": str(RL_POLICY_DIR),
    }, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
